// Simplified sea-ice grid for map rendering (lat/lon pairs with SIC)
export function generateSeaIceGrid(): SeaIceCell[] {
  const cells: SeaIceCell[] = [];
  // Generate a 6x12 grid over the Southern Ocean route area
  const latRange = [-65, -78];
  const lonRange = [55, 175];
  const latStep = 2;
  const lonStep = 10;

  for (let lat = latRange[0]; lat >= latRange[1]; lat -= latStep) {
    for (let lon = lonRange[0]; lon <= lonRange[1]; lon += lonStep) {
      // Synthetic SIC based on latitude (more ice further south)
      const baseSIC = Math.max(0, Math.min(1, (Math.abs(lat) - 62) / 20 + Math.random() * 0.15 - 0.05));
      const sic = Math.round(baseSIC * 100) / 100;
      let riskLevel: SeaIceCell['riskLevel'] = 'SAFE';
      let risk = sic * 80;
      if (risk <= 20) riskLevel = 'SAFE';
      else if (risk <= 40) riskLevel = 'LOW';
      else if (risk <= 60) riskLevel = 'MODERATE';
      else if (risk <= 80) riskLevel = 'HIGH';
      else riskLevel = 'CRITICAL';

      cells.push({
        lat,
        lon,
        sic,
        risk: Math.round(risk),
        riskLevel,
        trend: sic > 0.5 ? 'increasing' : sic > 0.3 ? 'stable' : 'decreasing',
      });
    }
  }
  return cells;
}

